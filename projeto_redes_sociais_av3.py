"""### Ligação com os filmes: título dentro do texto

Como as resenhas não dizem de qual filme falam, usamos uma regra simples: uma resenha "cita" um filme quando o título aparece no texto (sem diferenciar maiúsculas, acentos e pontuação, e só como palavra inteira). Para cada filme da base final, calculamos:

- `rev_mencoes`: quantas resenhas citam o título;
- `rev_pct_positivo`: porcentagem dessas resenhas que é positiva.

Cuidados para reduzir erros:
- Títulos curtos e de uma palavra só (como "Up" ou "Fury") aparecem em muitos textos sem falar do filme, então só usamos títulos com 2 ou mais palavras, ou com 10 ou mais letras.
- Títulos que se repetem na base (refilmagens com o mesmo nome) são descartados, porque não dá para saber de qual ano é a resenha.
- Só analisamos filmes com pelo menos `MIN_MENCOES` resenhas, pois uma porcentagem calculada com 1 ou 2 resenhas não é confiável.
"""

def normalizar(txt):
    """Minúsculas, sem acento e sem pontuação (para comparar títulos e textos)."""
    txt = unicodedata.normalize("NFKD", str(txt)).encode("ascii", "ignore").decode()
    txt = re.sub(r"[^a-z0-9]+", " ", txt.lower())
    return txt.strip()


def contar_mencoes(df_filmes, df_resenhas):
    """Para cada filme, conta as resenhas que citam o título e a % delas que é positiva."""
    # Texto com espaço nas pontas: buscar " titulo " garante palavra inteira
    textos = df_resenhas["review"].map(lambda t: f" {normalizar(t)} ")
    positivo = df_resenhas["positivo"].to_numpy()

    titulos = df_filmes[["movie_title", "title_year"]].drop_duplicates().copy()
    titulos["titulo_norm"] = titulos["movie_title"].map(normalizar)
    total = len(titulos)

    # Descarta títulos repetidos (refilmagens) e títulos curtos demais
    titulos = titulos[~titulos["titulo_norm"].duplicated(keep=False)]
    titulos = titulos[(titulos["titulo_norm"].str.split().str.len() >= 2) |
                      (titulos["titulo_norm"].str.len() >= 10)]
    print("Títulos na base final:", total, "| Usados na busca:", len(titulos))

    linhas = []
    for _, t in titulos.iterrows():
        achou = textos.str.contains(f" {t['titulo_norm']} ", regex=False).to_numpy()
        n = int(achou.sum())
        if n > 0:
            linhas.append({
                "movie_title": t["movie_title"],
                "title_year": t["title_year"],
                "rev_mencoes": n,
                "rev_pct_positivo": positivo[achou].mean(),
            })
    return pd.DataFrame(linhas, columns=["movie_title", "title_year", "rev_mencoes", "rev_pct_positivo"])


