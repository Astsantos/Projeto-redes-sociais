def classificar_forca(rho):
    """Classifica a força de uma correlação pelo valor absoluto."""
    a = abs(rho)
    if a < 0.10:
        return "desprezível"
    if a < 0.30:
        return "fraca"
    if a < 0.50:
        return "moderada"
    return "forte"


def correlacao_spearman(df, x, y):
    """Correlação de Spearman entre x e y, usando só as linhas que têm os dois valores.
    Usamos Spearman porque curtidas e bilheteria são muito assimétricas."""
    d = df[[x, y]].dropna()
    if len(d) < 10:
        return {"n": len(d), "rho": np.nan, "p": np.nan}
    rho, p = stats.spearmanr(d[x], d[y])
    return {"n": len(d), "rho": rho, "p": p}


def descrever_relacao(df, x, y, rotulo):
    """Imprime em uma frase o resultado da correlação entre x e y."""
    r = correlacao_spearman(df, x, y)
    if np.isnan(r["rho"]):
        print(f"{rotulo}: poucos dados (n = {r['n']}).")
        return r
    sentido = "positiva" if r["rho"] > 0 else "negativa"
    signif = "estatisticamente significativa" if r["p"] < ALFA else "não significativa"
    print(f"{rotulo}: Spearman = {r['rho']:.2f} (n = {r['n']}, p = {r['p']:.3g}) "
          f"-> relação {classificar_forca(r['rho'])} {sentido}, {signif}.")
    return r

